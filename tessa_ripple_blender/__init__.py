"""Tessa Ripple: encode a mesh's vertices with Moth's Tessa quantum encoder and read
them back, moving each vertex to where the readout puts it.

Modules:
    props    scene settings (scene.tessa)
    ops      operators; a run works in a thread and writes results on the main thread
    ui       sidebar panels (View3D > N > Tessa)
    engine   the quantum pipeline, numpy only (no bpy)
    mesh_io  Blender mesh <-> numpy, shape keys and error colours
    core/    generated by build_ext.py from ../tessa_ripple (do not edit here)
    tessa/   generated by build_ext.py: Moth's Tessa, vendored (MIT)

Nothing here imports qiskit at registration (so enabling the add-on is instant): a
one-shot timer a moment later imports it on the main thread (engine.prepare) and then
warms the rest on a background thread (engine.warm), so the first run is not slower
than later ones. A run started before that finishes simply does the same work itself.
"""

import threading

import bpy

from . import engine, ops, props, ui

CLASSES = props.CLASSES + ops.CLASSES + ui.CLASSES


def _preload():
    """One-shot timer: import qiskit on the main thread, warm the rest off it.

    Returns:
        None: so the timer does not repeat.
    """
    if ops.STATE["running"]:  # a run already loaded everything itself
        return None
    try:
        engine.prepare()
    except Exception:  # a missing wheel: the first run (and Check) report it
        return None

    def work():
        """Worker thread: engine.warm only, never bpy."""
        try:
            engine.warm()
        except Exception:  # best effort: the first run reports a real problem
            pass

    threading.Thread(target=work, daemon=True).start()
    return None


def register():
    """Register the classes and ``scene.tessa``, and schedule the preload."""
    for cls in CLASSES:
        bpy.utils.register_class(cls)
    bpy.types.Scene.tessa = bpy.props.PointerProperty(type=props.TessaSettings)
    bpy.app.timers.register(_preload, first_interval=1.5, persistent=False)


def unregister():
    """Stop a running worker and remove everything ``register`` added."""
    if bpy.app.timers.is_registered(_preload):
        bpy.app.timers.unregister(_preload)
    ops.STATE["cancel"] = True  # stop a running worker after its current readout
    del bpy.types.Scene.tessa
    for cls in reversed(CLASSES):
        bpy.utils.unregister_class(cls)
